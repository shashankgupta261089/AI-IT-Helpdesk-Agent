-- Run this once in the Supabase SQL Editor before using the app.
-- It creates the pgvector-backed RAG table, RPC function, and support ticket table.

create extension if not exists vector with schema extensions;

create table if not exists documents (
  id text primary key,
  content text,
  metadata jsonb,
  embedding extensions.vector(1536)
);

create or replace function match_documents(
  query_embedding extensions.vector(1536),
  match_count int default 5,
  filter jsonb default '{}'
)
returns table (
  id text,
  content text,
  metadata jsonb,
  embedding extensions.vector(1536),
  similarity float
)
language plpgsql
as $$
#variable_conflict use_column
begin
  return query
  select
    documents.id,
    documents.content,
    documents.metadata,
    documents.embedding,
    1 - (documents.embedding <=> query_embedding) as similarity
  from documents
  where documents.metadata @> filter
  order by documents.embedding <=> query_embedding
  limit match_count;
end;
$$;

create table if not exists support_tickets (
  ticket_number bigint generated by default as identity primary key,
  id text generated always as ('INC-' || (1000 + ticket_number)::text) stored unique,
  employee_name text not null,
  employee_number text not null,
  category text not null,
  priority text not null,
  summary text not null,
  status text not null default 'open',
  created_at timestamptz not null default now(),
  comments text not null default 'Created by AI IT Helpdesk Agent demo.'
);

create index if not exists support_tickets_employee_number_idx
on support_tickets (employee_number);

create index if not exists support_tickets_created_at_idx
on support_tickets (created_at desc);
